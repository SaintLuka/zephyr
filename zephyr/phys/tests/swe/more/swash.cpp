void Swash::leftcondition(int n, double hexl, double uexl) const{
	
	/**
	 * @details
	 * Saves the left boundary condition (h and q=hu) in the file transient_leftbc.txt or periodic_leftbc.txt.
	 * @param[in] n current time iteration
	 * @param[in] hexl left value of the water height
	 * @param[in] uexl left value of the velocity
	 */

	ofstream outsave(namefile.c_str(),ios::app);

	if (0==n){}
	else if (1==n){
		outsave << "if (time<"<< n*dt<<"){ hfix = "<<hexl<<"; qfix ="<<hexl*uexl<<"; }" << endl;
	}
	else if (n==nt){
		outsave << "else { hfix = "<<hexl<<"; qfix ="<<hexl*uexl<<"; }" << endl;
	}
	else{
		outsave << "else if (time<"<< n*dt<<"){ hfix = "<<hexl<<"; qfix ="<<hexl*uexl<<"; }" << endl;
	}

	outsave.close();

}

double Swash::J(int k, double x){

	/**
	 * @details
	 * Computes the value of the kth Bessel function (k=0,1 or 2) at x.
	 * @param[in] k the number of the Bessel function (k=0,1 or 2)
	 * @param[in] x the point to evaluate the Bessel function
	 */

	double j, tmp, x2;
	int kf;

	kf = max(1,k);
	j = pow((x/2),k)/kf;
	tmp = j;
	x2 = pow((x/2),2);
	for (int comp =1; comp <=30; comp ++){
		tmp *= -x2/(comp*(comp+k));
		j+=tmp;
	}
	return j;
}
